function updateUserProfile(message: string) {
  // Detectar interesses do usuário
  const interests = {
    'clima': ['clima', 'temperatura', 'aquecimento'],
    'energia': ['energia', 'solar', 'eólica', 'renovável'],
    'oceanos': ['oceano', 'mar', 'água'],
    'história': ['história', 'antigo', 'civilização'],
    'ciência': ['ciência', 'descoberta', 'pesquisa'],
    'tecnologia': ['tecnologia', 'computador', 'digital']
  };
  
  Object.entries(interests).forEach(([topic, keywords]) => {
    if (keywords.some(keyword => message.includes(keyword))) {
      if (!conversationHistory.topics.includes(topic)) {
        conversationHistory.topics.push(topic);
      }
      if (!conversationHistory.userInterests.includes(topic)) {
        conversationHistory.userInterests.push(topic);
      }
    }
  });
}

function getSuggestionBasedOnHistory(): string {
  const interests = conversationHistory.userInterests;
  
  if (interests.includes('clima')) {
    return "🌡️ **Aprofundar Clima**: Efeitos regionais, projeções futuras, soluções";
  }
  if (interests.includes('energia')) {
    return "⚡ **Expandir Energia**: Armazenamento, eficiência, inovações";
  }
  if (interests.includes('história')) {
    return "📚 **Conectar História**: Impactos ambientais de civilizações";
  }
  
  return "🌍 **Temas Relacionados**: Conexões entre seus interesses";
}

function getRandomResponse(category: keyof typeof responses): string {
  const categoryResponses = responses[category];
  let response;
  
  // Garantir resposta diferente da anterior
  do {
    response = categoryResponses[Math.floor(Math.random() * categoryResponses.length)];
  } while (response === lastResponse && categoryResponses.length > 1);
  
  lastResponse = response;
  
  // Personalizar resposta baseada no histórico
  const isReturningUser = conversationHistory.userMessages.length > 1;
  if (isReturningUser && conversationHistory.topics.includes(category)) {
    response = `Como você já demonstrou interesse neste tema, aqui estão detalhes adicionais:\n\n${response}`;
    
    // Adicionar conexão com tópicos anteriores
    const relatedTopics = getRelatedTopics(category);
    if (relatedTopics.length > 0) {
      response += `\n\n🔗 **Conexão**: Isso se relaciona com ${relatedTopics.join(' e ')} que discutimos antes.`;
    }
  }
  
  return response;
}

function getRelatedTopics(currentTopic: string): string[] {
  const connections: Record<string, string[]> = {
    'temperatura': ['clima', 'oceanos'],
    'clima': ['temperatura', 'energia'],
    'energia': ['clima', 'tecnologia'],
    'oceanos': ['temperatura', 'clima'],
    'historia': ['ciencia', 'tecnologia'],
    'ciencia': ['tecnologia', 'clima'],
    'tecnologia': ['ciencia', 'energia']
  };
  
  return connections[currentTopic]?.filter(topic => 
    conversationHistory.topics.includes(topic)
  ) || [];
}